CREATE TABLE IF NOT EXISTS mobile_corporate_tax_returns (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  company_id BIGINT UNSIGNED NOT NULL,
  taxable_person_name VARCHAR(200) NOT NULL,
  corporate_tax_trn VARCHAR(80) NOT NULL,
  taxable_person_type ENUM('Resident Person','Non-Resident Person','Qualifying Free Zone Person','Non-qualifying Free Zone Person','Tax Group') NOT NULL,
  tax_period_start DATE NOT NULL,
  tax_period_end DATE NOT NULL,
  accounting_standard VARCHAR(100) NOT NULL,
  audited_financial_statements TINYINT(1) NOT NULL DEFAULT 0,
  revenue DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  accounting_income DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  exempt_income DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  non_deductible_expenses DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  other_additions DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  other_deductions DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  tax_losses_brought_forward DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  tax_losses_used DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  qualifying_income DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  foreign_tax_credits DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  claim_small_business_relief TINYINT(1) NOT NULL DEFAULT 0,
  taxable_income_before_losses DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  taxable_income DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  tax_liability DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  corporate_tax_payable DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  filing_deadline DATE NOT NULL,
  notes TEXT NULL,
  created_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_mobile_ct_period(company_id,tax_period_start,tax_period_end),
  INDEX idx_mobile_ct_company_end(company_id,tax_period_end),
  CONSTRAINT fk_mobile_ct_company FOREIGN KEY(company_id) REFERENCES companies(id) ON DELETE CASCADE,
  CONSTRAINT fk_mobile_ct_user FOREIGN KEY(created_by) REFERENCES users(id)
);
